let lang = 'en';

export function initLang() {
  try {
    const s = localStorage.getItem(LANG_KEY);
    if (s === 'vi' || s === 'en') lang = s;
  } catch { /* storage unavailable: session-only */ }
  document.documentElement.lang = lang;
}

export function getLang() { return lang; }
export function isVi() { return lang === 'vi'; }
export function otherLang() { return lang === 'en' ? 'vi' : 'en'; }

export function setLang(l) {
  lang = l === 'vi' ? 'vi' : 'en';
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* session-only */ }
  applyStatic();
}

export function t(key, params) {
  let s = UI[lang]?.[key] ?? UI.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

// Translate a chemistry check result: string (legacy) or { key, p }.
export function trReason(r) {
  if (!r) return '';
  if (typeof r === 'string') return r;
  return t(r.key, r.p);
}

export function elName(el) {
  if (lang === 'vi') { const n = EL_VI[el.z]; if (n) return n; }
  return el.name;
}

export function catLabel(cat) {
  return (lang === 'vi' ? CAT_VI[cat] : CAT_EN[cat]) || cat;
}

export function applyStatic() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
